# Sección 4 - Variables
# Ejercicio: Las manzanas de Juan, María y Adán

# Crear las variables y asignar la cantidad de manzanas
john = 3
mary = 5
adam = 6

# Imprimir las cantidades de manzanas en una misma línea
print(john, mary, adam, sep=", ")

# Calcular el total de manzanas
total_apples = john + mary + adam

# Imprimir el total
print(total_apples)

# Imprimir un mensaje junto con el total de manzanas
print("Número total de manzanas:", total_apples)

# Experimentación con variables y operaciones aritméticas

oranges = 10
pears = 4

print("Suma:", oranges + pears)
print("Resta:", oranges - pears)
print("Multiplicación:", oranges * pears)
print("División:", oranges / pears)
print("División entera:", oranges // pears)
print("Módulo:", oranges % pears)